namespace Aeternum.WorldGen.Models;

// Закон наследования престола — принадлежит культуре правящего дома (см. Culture),
// а не государству: трон переходит по обычаю народа, а не по указу
public enum SuccessionLaw
{
    Seniority,      // Старшинство: корона старейшему живому члену дома (исходный и самый простой обычай)
    Primogeniture,  // Первородство: корона старшему ребёнку прежнего правителя, и лишь затем — прочей родне
    Election        // Выборность: дом сам выдвигает достойнейшего — того, за кем больше связей и славы
}
