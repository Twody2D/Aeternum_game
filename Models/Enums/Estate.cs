namespace Aeternum.WorldGen.Models;

// Сословие — положение человека в обществе. Нигде не хранится и не назначается
// при рождении: вычисляется по тому, кем человек приходится миру прямо сейчас
// (см. EstateSystem). Поэтому оно и меняется вместе с судьбой — угасший дом
// перестаёт быть знатью, а поднявшийся становится
public enum Estate
{
    Nobility,  // Правящие дома и те, кто служит при короне
    Burghers,  // Ремесло, торговля и учёность — те, кто живёт умением
    Commoners  // Все прочие: земля, подённая работа, военная служба рядовым
}
