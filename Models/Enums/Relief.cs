namespace Aeternum.WorldGen.Models;

// Рельеф места — как и плодородие (см. Climate), нигде не хранится: целиком
// выводится из координат поселения и зерна мира (см. TerrainSystem)
public enum Relief
{
    Lowland, // Низина — ровная земля, ничем не примечательна
    Hill,    // Холмы — небольшая прибавка к обороне
    Mountain, // Горы — скупая земля, но её трудно взять
    Coast    // Морской берег или речная пойма — щедрая земля и бойкая торговля
}
