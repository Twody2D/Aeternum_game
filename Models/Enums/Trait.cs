namespace Aeternum.WorldGen.Models;

// Черта характера — фиксируется при рождении/создании персонажа и не меняется всю
// жизнь (см. CharacterGenerator.AssignTraits). Влияет на веса в существующих
// системах, а не создаёт новую механику
public enum Trait
{
    Hardworking, // Трудолюбивый — выше производство еды и материалов
    Frail,       // Слабое здоровье — выше риск несчастного случая
    Brave,       // Смелый — выше риск несчастного случая, охотнее переезжает, чаще бросает вызов правителю
    Prudent      // Осторожный — ниже риск несчастного случая, реже переезжает
}
