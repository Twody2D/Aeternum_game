namespace Aeternum.WorldGen.Models;

// Язык поселения. Не то же самое, что культура: на одном языке говорят
// несколько родственных культур, поэтому языков в мире всегда меньше, чем
// народов, и языковая граница не совпадает с культурной.
//
// Язык принадлежит месту, а не человеку и не культуре: поселение может
// перейти на язык соседей, не меняя обычаев (см. LanguageSystem)
public class Language
{
    public int Id { get; set; }

    public string Name { get; set; } = "";
}
