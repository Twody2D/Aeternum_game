namespace Aeternum.WorldGen.Models;

// Тип события мира, см. WorldEvent
public enum EventType
{
    Birth,             // Рождение ребёнка
    Death,             // Смерть персонажа
    Marriage,          // Заключение брака
    Divorce,           // Развод
    CreationOfDynasty, // Основание новой династии
    Migration,         // Переезд в другое поселение
    CreationOfKingdom, // Образование государства
    Succession,        // Смена правителя государства
    Disaster,          // Катастрофа (эпидемия или неурожай)
    War,               // Война за спорное поселение
    FallOfKingdom,     // Государство пало — правящая династия угасла
    Colonization,      // Семья основала новое поселение из-за переполнения
    Murder,            // Заговор против правителя
    Alliance,          // Союз между государствами
    CivilWar,          // Кризис наследования — распря, если трон ушёл не к прямому потомку
    Guardianship,      // Ребёнок, оставшийся без родителей, взят под опеку
    AllianceBroken,    // Союз распался — правящие дома разошлись в вере
    Peace,             // Затянувшаяся осада закончилась перемирием
    Vassalization,     // Слабая сторона спора признала вассалитет сильной вместо продолжения войны
    Rebellion,         // Жители поселения отказали короне в повиновении
    Schism,            // Изолированная община откололась от прежней веры
    Era,               // Накопленное знание вывело мир в новую эпоху
    Suppression,       // Корона подавила мятеж силой
    Independence,      // Вассал перерос сюзерена и сбросил зависимость
    Relief,            // Корона раздала хлеб из казны голодающим землям
    Appointment        // Государство обрело нового наследника, воеводу, казначея или советника
}
